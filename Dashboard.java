    private void btn_vincularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_vincularActionPerformed
        int linhaSkill = tabela_skills.getSelectedRow();
        int linhaAgente = tabela_agentes.getSelectedRow();

        if (linhaSkill != -1 && linhaAgente != -1) {
            int idSkill = (int) tabela_skills.getValueAt(linhaSkill, 0);
            int idAgente = (int) tabela_agentes.getValueAt(linhaAgente, 0);
            boolean sucesso = new OrquestradorDAO().vincular(idAgente, idSkill);

            if (sucesso) {
                javax.swing.JOptionPane.showMessageDialog(this, "Habilidade vinculada com sucesso!");
                atualizarTudo();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Aviso: Este agente já possui esta habilidade.");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma skill E um agente.");
        }
    }//GEN-LAST:event_btn_vincularActionPerformed

    private void btn_editar_skillActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editar_skillActionPerformed
        int linha = tabela_skills.getSelectedRow();
        if (linha != -1) {
            int idSkill = (int) tabela_skills.getValueAt(linha, 0);
            String nomeAtual = (String) tabela_skills.getValueAt(linha, 1);
            String categoriaAtual = (String) tabela_skills.getValueAt(linha, 2);

            String novoNome = javax.swing.JOptionPane.showInputDialog(this, "Novo nome da Skill:", nomeAtual);
            String novaCategoria = javax.swing.JOptionPane.showInputDialog(this, "Nova Categoria:", categoriaAtual);

            if (novoNome != null && novaCategoria != null && !novoNome.trim().isEmpty()) {
                new OrquestradorDAO().atualizarHabilidade(idSkill, novoNome.trim(), novaCategoria.trim());
                atualizarTudo();
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma skill.");
        }
    }//GEN-LAST:event_btn_editar_skillActionPerformed

    private void btn_excluir_skillActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_excluir_skillActionPerformed
        int linha = tabela_skills.getSelectedRow();
        if (linha != -1) {
            int idSkill = (int) tabela_skills.getValueAt(linha, 0);
            String nomeSkill = (String) tabela_skills.getValueAt(linha, 1);

            int conf = javax.swing.JOptionPane.showConfirmDialog(this, "Deseja excluir a skill '" + nomeSkill + "'?", "Aviso", javax.swing.JOptionPane.YES_NO_OPTION);
            if (conf == javax.swing.JOptionPane.YES_OPTION) {
                new OrquestradorDAO().excluirHabilidade(idSkill);
                atualizarTudo();
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma skill.");
        }
    }//GEN-LAST:event_btn_excluir_skillActionPerformed

    private void btn_editar_agenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editar_agenteActionPerformed
        int linha = tabela_agentes.getSelectedRow();

        if (linha != -1) {
            int idAgente = (int) tabela_agentes.getValueAt(linha, 0);
            String nomeAtual = (String) tabela_agentes.getValueAt(linha, 1);

            String novoNome = javax.swing.JOptionPane.showInputDialog(this, "Novo nome do Agente:", nomeAtual);

            if (novoNome != null && !novoNome.trim().isEmpty()) {
                new OrquestradorDAO().atualizarAgente(idAgente, novoNome.trim());
                atualizarTudo(); 
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um agente na tabela para editar.");
        }

    }//GEN-LAST:event_btn_editar_agenteActionPerformed

    private void btn_excluir_agenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_excluir_agenteActionPerformed
        int linha = tabela_agentes.getSelectedRow();

        if (linha != -1) {
            int idAgente = (int) tabela_agentes.getValueAt(linha, 0);
            String nomeAgente = (String) tabela_agentes.getValueAt(linha, 1);

            int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "Deseja excluir o agente '" + nomeAgente + "'? (Os vínculos associados a ele também serão removidos)",
                    "Confirmação",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

            if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
                new OrquestradorDAO().excluirAgente(idAgente);
                atualizarTudo(); 
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um agente na tabela para excluir.");
        }

    }//GEN-LAST:event_btn_excluir_agenteActionPerformed

