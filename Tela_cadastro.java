    private void btn_cadastrar_agenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cadastrar_agenteActionPerformed
        String nome = input_nomeAgente.getText();

        if (!nome.trim().isEmpty()) {
            OrquestradorDAO dao = new OrquestradorDAO();
            dao.cadastrarAgente(nome);

            JOptionPane.showMessageDialog(this, "Agente cadastrado com sucesso!");
            input_nomeAgente.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Preencha o nome do agente.");
        }
    }//GEN-LAST:event_btn_cadastrar_agenteActionPerformed

    private void btn_cadastrar_skillActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cadastrar_skillActionPerformed
        String nome = input_nomeSkill.getText();
        String categoria = input_categoria.getText();

        if (!nome.trim().isEmpty() && !categoria.trim().isEmpty()) {
            OrquestradorDAO dao = new OrquestradorDAO();
            dao.cadastrarHabilidade(nome, categoria);

            JOptionPane.showMessageDialog(this, "Habilidade salva com sucesso!");

            input_nomeSkill.setText("");
            input_categoria.setText("");

        } else {
            JOptionPane.showMessageDialog(this, "Preencha o nome e a categoria.");
        }
    }//GEN-LAST:event_btn_cadastrar_skillActionPerformed

