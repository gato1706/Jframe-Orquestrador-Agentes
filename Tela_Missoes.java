    private void btn_criar_missaoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_criar_missaoActionPerformed
        if (cb_clientes.getSelectedItem() != null) {
            String nomeClienteSelecionado = (String) cb_clientes.getSelectedItem();
            String desc = txa_descricao.getText();

            if (!desc.trim().isEmpty()) {
                int idCliente = 0;
                for (ItemCombo c : new OrquestradorDAO().listarClientes()) {
                    if (c.getNome().equals(nomeClienteSelecionado)) {
                        idCliente = c.getId();
                        break;
                    }
                }

                if (idCliente > 0) {
                    new OrquestradorDAO().cadastrarMissao(idCliente, desc);
                    txa_descricao.setText("");

                    javax.swing.JOptionPane.showMessageDialog(this, "Missão criada com sucesso!");

                    atualizarListas();
                    cb_missoes.setSelectedIndex(cb_missoes.getItemCount() - 1);
                }
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor, digite uma descrição para a missão!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_btn_criar_missaoActionPerformed

    private void btn_alocarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_alocarActionPerformed
        int linha = tabela_agentes_disponiveis.getSelectedRow();
        if (linha != -1 && cb_missoes.getSelectedItem() != null) {
            int idAgente = (int) tabela_agentes_disponiveis.getValueAt(linha, 0);
            String nomeMissao = (String) cb_missoes.getSelectedItem();

            int idMissao = 0;
            for (ItemCombo m : new OrquestradorDAO().listarMissoes()) {
                if (m.getNome().equals(nomeMissao)) {
                    idMissao = m.getId();
                    break;
                }
            }

            if (idMissao > 0) {
                new OrquestradorDAO().alocarAgenteNaMissao(idMissao, idAgente);
                atualizarTabelas();
            }
        }
    }//GEN-LAST:event_btn_alocarActionPerformed

