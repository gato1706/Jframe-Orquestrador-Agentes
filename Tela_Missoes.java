    private void btn_pdfActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_pdfActionPerformed
        if (cb_missoes.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma missão primeiro!");
            return;
        }
        if (tabela_equipe.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "A equipe está vazia! Aloque agentes antes de exportar.");
            return;
        }
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Salvar Relatório de Missão");
        int userSelection = fileChooser.showSaveDialog(this);

        if (userSelection == JFileChooser.APPROVE_OPTION) {
            File arquivoSalvar = fileChooser.getSelectedFile();
            String caminho = arquivoSalvar.getAbsolutePath();

            if (!caminho.toLowerCase().endsWith(".pdf")) {
                caminho += ".pdf";
            }

            try {
                Document documento = new Document();
                PdfWriter.getInstance(documento, new FileOutputStream(caminho));
                documento.open();

                // Definição simples de fontes
                Font fonteTitulo = new Font(Font.FontFamily.HELVETICA, 16, Font.BOLD);
                Font fonteSubtitulo = new Font(Font.FontFamily.HELVETICA, 12, Font.BOLD);
                Font fonteTexto = new Font(Font.FontFamily.HELVETICA, 11, Font.NORMAL);

                String nomeMissao = (String) cb_missoes.getSelectedItem();
                int idMissao = 0;
                OrquestradorDAO dao = new OrquestradorDAO();
                for (ItemCombo m : dao.listarMissoes()) {
                    if (m.getNome().equals(nomeMissao)) {
                        idMissao = m.getId();
                        break;
                    }
                }
                String descMissao = dao.getDescricaoMissao(idMissao);
                documento.add(new Paragraph("RELATÓRIO DE OPERAÇÃO\n\n", fonteTitulo));
                documento.add(new Paragraph("Missão: " + nomeMissao, fonteSubtitulo));
                documento.add(new Paragraph("Descrição: " + descMissao + "\n\n", fonteTexto));
                documento.add(new Paragraph("Agentes Alocados (" + tabela_equipe.getRowCount() + "):\n\n", fonteSubtitulo));
                PdfPTable tabelaPdf = new PdfPTable(tabela_equipe.getColumnCount());
                tabelaPdf.setWidthPercentage(100);
                tabelaPdf.setWidths(new float[]{15f, 85f}); 
                for (int i = 0; i < tabela_equipe.getColumnCount(); i++) {
                    PdfPCell celulaCabecalho = new PdfPCell(new Phrase(tabela_equipe.getColumnName(i), fonteSubtitulo));
                    celulaCabecalho.setBackgroundColor(BaseColor.LIGHT_GRAY);
                    celulaCabecalho.setPadding(6);
                    tabelaPdf.addCell(celulaCabecalho);
                }
                for (int linhas = 0; linhas < tabela_equipe.getRowCount(); linhas++) {
                    for (int colunas = 0; colunas < tabela_equipe.getColumnCount(); colunas++) {
                        Object valor = tabela_equipe.getModel().getValueAt(linhas, colunas);
                        PdfPCell celulaDado = new PdfPCell(new Phrase(valor != null ? valor.toString() : "", fonteTexto));
                        celulaDado.setPadding(5);
                        tabelaPdf.addCell(celulaDado);
                    }
                }
                documento.add(tabelaPdf);
                documento.close();
                javax.swing.JOptionPane.showMessageDialog(this, "PDF gerado com sucesso em:\n" + caminho);
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao gerar PDF: " + e.getMessage());
            }
        }

    }//GEN-LAST:event_btn_pdfActionPerformed

