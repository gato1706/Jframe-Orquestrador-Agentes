    private void atualizarListas() {
        OrquestradorDAO dao = new OrquestradorDAO();

        cb_clientes.removeAllItems();
        for (ItemCombo c : dao.listarClientes()) {
            cb_clientes.addItem(c.getNome()); // Adiciona o nome como String
        }

        cb_missoes.removeAllItems();
        for (ItemCombo m : dao.listarMissoes()) {
            cb_missoes.addItem(m.getNome()); // Adiciona o resumo como String
        }
    }

    private void atualizarTabelas() {
        OrquestradorDAO dao = new OrquestradorDAO();

        DefaultTableModel modelAgentes = (DefaultTableModel) tabela_agentes_disponiveis.getModel();
        dao.carregarTabelaAgentes(modelAgentes);

        DefaultTableModel modelEquipe = (DefaultTableModel) tabela_equipe.getModel();

        if (cb_missoes.getSelectedItem() != null) {
            String nomeMissao = (String) cb_missoes.getSelectedItem();
            int idMissao = 0;

            for (ItemCombo m : dao.listarMissoes()) {
                if (m.getNome().equals(nomeMissao)) {
                    idMissao = m.getId();
                    break;
                }
            }

            if (idMissao > 0) {
                dao.carregarTabelaEquipe(modelEquipe, idMissao);
                lbl_total_agentes.setText("Total de agentes alocados: " + modelEquipe.getRowCount());

                // NOVO: Mostra a descrição na tela!
                lbl_desc_missao.setText("Descrição: " + dao.getDescricaoMissao(idMissao));
            } else {
                modelEquipe.setRowCount(0);
                lbl_total_agentes.setText("Total de agentes alocados: 0");
                lbl_desc_missao.setText("Descrição: ");
            }
        } else {
            modelEquipe.setRowCount(0);
            lbl_total_agentes.setText("Total de agentes alocados: 0");
            lbl_desc_missao.setText("Descrição: ");
        }
    }

